#!/usr/bin/env python3
"""Generate CREDITS.md from the provenance table.

Never hand-edit CREDITS.md — it is regenerated from
``mcp/data/provenance.json`` by this script.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from provenance import (  # noqa: E402
    PROJECT_ROOT,
    entries_needing_review,
    load_provenance,
)

CREDITS_PATH = PROJECT_ROOT / "CREDITS.md"
DATA_DIR = PROJECT_ROOT / "mcp" / "data"


def write_credits() -> int:
    entries = load_provenance()

    if not entries:
        print("No provenance entries found.", file=sys.stderr)
        CREDITS_PATH.write_text(
            "# Credits\n\nNo vendored content recorded.\n", encoding="utf-8"
        )
        return 0

    by_license: dict[str, list[dict]] = defaultdict(list)
    for entry in entries:
        by_license[entry.get("license") or "UNKNOWN"].append(entry)

    lines: list[str] = []
    lines.append("# Credits")
    lines.append("")
    lines.append(
        "This file is generated by `mcp/build/write_credits.py` from "
        "`mcp/data/provenance.json`. Do not edit it by hand."
    )
    lines.append("")
    lines.append(
        f"{len(entries)} entries: "
        f"{sum(1 for e in entries if e.get('kind') == 'skill')} skills, "
        f"{sum(1 for e in entries if e.get('kind') == 'agent')} agents."
    )
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Licence | Count |")
    lines.append("|---|---|")
    for license_name in sorted(by_license):
        lines.append(f"| {license_name} | {len(by_license[license_name])} |")
    lines.append("")

    lines.append("## Authored content")
    lines.append("")
    authored = [e for e in entries if e.get("source") == "authored"]
    if authored:
        lines.append(
            "Written for this project and released under the repository's MIT "
            "licence."
        )
        lines.append("")
        for entry in sorted(authored, key=lambda e: (e["kind"], e["name"])):
            lines.append(f"- **{entry['name']}** ({entry['kind']})")
    else:
        lines.append("None.")
    lines.append("")

    lines.append("## Vendored content")
    lines.append("")
    vendored = [e for e in entries if e.get("source") != "authored"]
    if not vendored:
        lines.append("None.")
        lines.append("")
    else:
        lines.append(
            "Copied from upstream repositories. Each entry keeps the licence "
            "of its origin."
        )
        lines.append("")
        for license_name in sorted(by_license):
            group = [e for e in vendored if (e.get("license") or "UNKNOWN") == license_name]
            if not group:
                continue
            lines.append(f"### {license_name}")
            lines.append("")
            for entry in sorted(group, key=lambda e: e["name"]):
                owner = entry.get("owner") or "unknown"
                upstream = entry.get("upstream") or entry.get("source") or "unknown"
                lines.append(f"- **{entry['name']}** — {owner}")
                lines.append(f"  - Source: {upstream}")
                lines.append(f"  - Path: `{entry.get('path', '')}`")
            lines.append("")

    review = entries_needing_review(entries)
    if review:
        lines.append("## Needs review")
        lines.append("")
        lines.append(
            "These entries have a licence that was not in the known set. "
            "They are excluded from the corpus until reviewed."
        )
        lines.append("")
        for entry in sorted(review, key=lambda e: e["name"]):
            lines.append(
                f"- **{entry['name']}** — {entry.get('license') or 'no licence detected'}"
            )
        lines.append("")

    CREDITS_PATH.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {CREDITS_PATH.relative_to(PROJECT_ROOT)} ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(write_credits())
