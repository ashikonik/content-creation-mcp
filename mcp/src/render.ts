/**
 * Dialect rendering.
 *
 * This is the harness-agnostic core of the server: the same skill is rendered
 * into whichever format the calling client understands. Nothing here touches
 * the filesystem — every render returns a string the client decides what to
 * do with.
 */
import { stringify as stringifyYaml } from "yaml";
import { buildFrontmatter, oneLine, parseFrontmatter } from "./frontmatter.js";
import type {
  AgentRecord,
  RenderFormat,
  SkillFrontmatter,
  SkillRecord,
} from "./types.js";

export interface RenderContext {
  frontmatter: SkillFrontmatter;
  body: string;
  record: SkillRecord;
}

/** Description trimmed to a single line for machine-readable headers. */
function descriptionOf(fm: SkillFrontmatter): string {
  return oneLine(fm.description);
}

/**
 * Markdown — plain body with a short header. The most portable format.
 */
function renderMarkdown(ctx: RenderContext): string {
  return ctx.body.trimEnd() + "\n";
}

/**
 * Claude frontmatter — name + description + allowed-tools, matching the
 * format Claude Code expects in a SKILL.md.
 */
function renderClaudeFrontmatter(ctx: RenderContext): string {
  const fm = ctx.frontmatter;
  const header = buildFrontmatter([
    ["name", fm.name],
    ["description", descriptionOf(fm)],
    ["allowed-tools", fm.allowed_tools],
    ["license", fm.license],
    ["version", fm.version],
  ]);
  return `${header}\n${ctx.body.trimEnd()}\n`;
}

/**
 * OpenAI YAML — an interface + policy envelope around the instructions.
 */
function renderOpenAiYaml(ctx: RenderContext): string {
  const fm = ctx.frontmatter;
  const doc = {
    interface: {
      name: fm.name,
      description: descriptionOf(fm),
    },
    policy: {
      compatibility: fm.compatibility ?? "openai-compatible-mcp-client",
      allowed_tools: fm.allowed_tools ?? [],
      requires: [],
      notes:
        "Generated by content-creation-mcp. The body below is the skill " +
        "instruction set, preserved verbatim.",
    },
    metadata: {
      content_domain: ctx.record.content_domain,
      source: ctx.record.source,
      prompt_signals: fm.metadata?.promptSignals?.phrases ?? [],
    },
    instructions: ctx.body.trimEnd(),
  };

  return stringifyYaml(doc, { lineWidth: 0 });
}

/**
 * Agents.md — a named section with marker comments so a harness can find
 * and replace a single skill in a larger agents file.
 */
function renderAgentsMd(ctx: RenderContext): string {
  const fm = ctx.frontmatter;
  const marker = `<!-- skills-library:name:${fm.name} -->`;
  const endMarker = `<!-- skills-library:end:${fm.name} -->`;

  const header = [
    marker,
    `## ${fm.name}`,
    "",
    `**Domain:** ${ctx.record.content_domain}  `,
    `**Source:** ${ctx.record.source}  `,
    `**Triggers:** ${(fm.metadata?.promptSignals?.phrases ?? []).join(" · ")}`,
    "",
    descriptionOf(fm),
    "",
  ].join("\n");

  return `${header}\n${ctx.body.trimEnd()}\n${endMarker}\n`;
}

/**
 * Cursor rules — plain prose under a rule heading, which is what a `.mdc`
 * rules file expects.
 */
function renderCursorRules(ctx: RenderContext): string {
  const fm = ctx.frontmatter;
  const signals = fm.metadata?.promptSignals?.phrases ?? [];

  const header = [
    `# ${fm.name}`,
    "",
    descriptionOf(fm),
    "",
    signals.length > 0 ? `Apply when: ${signals.join(", ")}.` : "",
    "",
    "---",
    "",
  ]
    .filter((line) => line !== "")
    .join("\n");

  return `${header}\n${ctx.body.trimEnd()}\n`;
}

export function renderSkill(
  format: RenderFormat,
  ctx: RenderContext,
): string {
  switch (format) {
    case "markdown":
      return renderMarkdown(ctx);
    case "claude-frontmatter":
      return renderClaudeFrontmatter(ctx);
    case "openai-yaml":
      return renderOpenAiYaml(ctx);
    case "agentsmd":
      return renderAgentsMd(ctx);
    case "cursor-rules":
      return renderCursorRules(ctx);
    default:
      throw new Error(`Unknown render format: ${format}`);
  }
}

/**
 * Assemble a runnable prompt for an agent.
 *
 * MCP has no agent-delegation primitive, so the server's job is to hand back
 * everything a client needs to run the agent itself: the system prompt, the
 * tool list, and the skills the agent will need to consult.
 */
export interface AgentRun {
  agent: AgentRecord;
  prompt: string;
  tools: string[];
  suggested_skills: string[];
}

export function runAgent(
  agent: AgentRecord,
  body: string,
  task: string,
  context: string | undefined,
  index: { skills: SkillRecord[] },
): AgentRun {
  const agentTokens = new Set(
    [
      ...agent.description.toLowerCase().split(/\W+/),
      ...agent.name.toLowerCase().split(/[-_]/),
    ].filter((t) => t.length > 3),
  );

  // Suggest skills whose domain matches the agent, ranked by token overlap.
  const suggested = index.skills
    .map((skill) => {
      let overlap = 0;
      const haystack = `${skill.name} ${skill.description}`.toLowerCase();
      for (const token of agentTokens) {
        if (haystack.includes(token)) overlap += 1;
      }
      if (skill.content_domain === agent.content_domain) overlap += 2;
      return { skill, score: overlap };
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5)
    .map((entry) => entry.skill.id);

  const parts = [
    `# Agent: ${agent.name}`,
    "",
    agent.description,
    "",
    "## Task",
    "",
    task,
  ];

  if (context) {
    parts.push("", "## Context", "", context);
  }

  parts.push(
    "",
    "## Available tools",
    "",
    agent.tools.length > 0
      ? agent.tools.map((t) => `- ${t}`).join("\n")
      : "- (none specified)",
    "",
    "## Skills to consult",
    "",
    suggested.length > 0
      ? suggested.map((s) => `- ${s}`).join("\n")
      : "- (none matched)",
    "",
    "## Instructions",
    "",
    body.trimEnd(),
    "",
  );

  return {
    agent,
    prompt: parts.join("\n"),
    tools: agent.tools,
    suggested_skills: suggested,
  };
}

/** Parse a SKILL.md file into a render context. */
export function contextFromFile(
  text: string,
  record: SkillRecord,
): RenderContext {
  const { frontmatter, body } = parseFrontmatter(text);
  return { frontmatter, body, record };
}
